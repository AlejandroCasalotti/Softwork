# -*- coding: utf-8 -*-
"""
Softwork Commerce Engine (SCE)

Notification Service

Central notification manager for SCE.

Responsible for:

- Email notifications
- Template rendering
- Recipient resolution
- Notification dispatch

Future versions:

- WhatsApp
- Telegram
- Slack
- Microsoft Teams
- Discord
"""

from __future__ import annotations

import logging

from odoo import api, models

_logger = logging.getLogger(__name__)


class SCENotificationService(models.AbstractModel):
    """
    Central notification service.

    Every notification generated by SCE
    should pass through this service.
    """

    _name = "sce.notification.service"

    _description = "SCE Notification Service"

    # =========================================================
    # Template Resolution
    # =========================================================

    @api.model
    def get_template(self, xmlid):
        """
        Returns a mail template.

        Returns False if template
        does not exist.
        """

        try:
            return self.env.ref(xmlid)

        except Exception:

            _logger.warning(
                "Notification template not found: %s",
                xmlid,
            )

            return False

    # =========================================================
    # Recipient Resolution
    # =========================================================

    @api.model
    def get_recipient(self, record):
        """
        Resolves recipient email.

        Priority

        account.user

        record.create_uid

        current user
        """

        if hasattr(record, "account_id"):

            account = record.account_id

            if account:

                if hasattr(account, "user_id"):

                    if account.user_id.email:

                        return account.user_id.email

        if record.create_uid:

            if record.create_uid.email:

                return record.create_uid.email

        return self.env.user.email

    # =========================================================
    # Email Sender
    # =========================================================

    @api.model
    def send_email(
        self,
        template_xmlid,
        record,
        email_to=None,
        force_send=True,
    ):
        """
        Sends an email using a template.
        """

        template = self.get_template(
            template_xmlid
        )

        if not template:

            return False

        destination = (
            email_to
            or
            self.get_recipient(record)
        )

        values = {

            "email_to": destination,

        }

        template.send_mail(

            record.id,

            force_send=force_send,

            email_values=values,

        )

        _logger.info(

            "Notification sent (%s) -> %s",

            template_xmlid,

            destination,

        )

        return True

    # =========================================================
    # Raw Email
    # =========================================================

    @api.model
    def send_message(
        self,
        subject,
        body,
        email_to,
        email_from=None,
        force_send=True,
    ):
        """
        Sends a plain email.
        """

        values = {

            "subject": subject,

            "body_html": body,

            "email_to": email_to,

            "email_from":
                email_from
                or
                self.env.user.email_formatted,

        }

        mail = self.env[
            "mail.mail"
        ].create(values)

        if force_send:

            mail.send()

        return mail

    # =========================================================
    # Template Renderer
    # =========================================================

    @api.model
    def render(
        self,
        template_xmlid,
        record,
    ):
        """
        Renders a template.

        Useful for previews.
        """

        template = self.get_template(
            template_xmlid
        )

        if not template:

            return False

        return template._render_field(

            "body_html",

            [record.id],

        )[record.id]

    # =========================================================
    # Generic Notification
    # =========================================================

    @api.model
    def notify(
        self,
        template_xmlid,
        record,
        email_to=None,
    ):
        """
        Generic notification entrypoint.
        """

        return self.send_email(

            template_xmlid,

            record,

            email_to=email_to,

        )

