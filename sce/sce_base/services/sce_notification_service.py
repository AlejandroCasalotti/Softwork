    # =========================================================
    # System Notifications
    # =========================================================

    @api.model
    def notify_system_alert(self, log):
        """
        Critical system event.
        """

        return self.notify(
            "sce_base.mail_template_sce_system_alert",
            log,
        )

    # =========================================================
    # Generic Log Notifications
    # =========================================================

    @api.model
    def notify_log(self, log):
        """
        Sends notification according to log level.
        """

        if log.level == "critical":

            return self.notify_system_alert(
                log
            )

        if log.level == "error":

            return self.notify_connector_error(
                log
            )

        return True

    # =========================================================
    # Exception Notification
    # =========================================================

    @api.model
    def notify_exception(
        self,
        exception,
        record=None,
    ):
        """
        Creates a log entry and
        notifies administrators.
        """

        log = self.env[
            "sce.log"
        ].log_exception(
            exception,
        )

        return self.notify_system_alert(
            log
        )

    # =========================================================
    # Batch Notifications
    # =========================================================

    @api.model
    def notify_many(
        self,
        template_xmlid,
        records,
    ):
        """
        Sends the same notification
        to multiple records.
        """

        total = 0

        for record in records:

            if self.notify(
                template_xmlid,
                record,
            ):

                total += 1

        return total

    # =========================================================
    # Notification Dispatcher
    # =========================================================

    @api.model
    def dispatch(
        self,
        notification_type,
        record,
    ):
        """
        Generic dispatcher.
        """

        mapping = {

            "job_failed":
                self.notify_job_failed,

            "queue_failed":
                self.notify_queue_failed,

            "oauth_expired":
                self.notify_oauth_expired,

            "connector_error":
                self.notify_connector_error,

            "system_alert":
                self.notify_system_alert,

            "webhook_failed":
                self.notify_webhook_failed,

        }

        handler = mapping.get(
            notification_type
        )

        if not handler:

            _logger.warning(

                "Unknown notification type: %s",

                notification_type,

            )

            return False

        return handler(
            record
        )